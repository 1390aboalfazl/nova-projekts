import json
from ..ast_nodes import Let, Show, Literal, Name, Unary, Binary
from ..semantic import infer

C_TYPES = {"Int": "int64_t", "Float": "double", "Bool": "bool", "Text": "char *"}

def c_string(value):
    return json.dumps(value, ensure_ascii=True)

def expr_to_c(expr, symbols):
    if isinstance(expr, Literal):
        if expr.literal_type == "Text": return c_string(expr.value)
        if expr.literal_type == "Bool": return "true" if expr.value else "false"
        if expr.literal_type == "Float":
            value = repr(expr.value)
            return value if "." in value or "e" in value.lower() else value + ".0"
        return str(expr.value)
    if isinstance(expr, Name): return expr.value
    if isinstance(expr, Unary): return f"(-{expr_to_c(expr.operand, symbols)})"
    if isinstance(expr, Binary):
        left, right = expr_to_c(expr.left, symbols), expr_to_c(expr.right, symbols)
        if expr.operator == "/" and infer(expr.left, symbols) == infer(expr.right, symbols) == "Int":
            return f"((double)({left}) / (double)({right}))"
        return f"({left} {expr.operator} {right})"
    raise TypeError("unknown expression")

def generate(program, symbols):
    out = ["/* Generated by Nova v0.1. Do not edit by hand. */",
           "#include <stdint.h>", "#include <stdbool.h>", "#include <stdio.h>", "",
           "int main(void) {"]
    for stmt in program.statements:
        if isinstance(stmt, Let):
            value = expr_to_c(stmt.value, symbols)
            if stmt.declared_type == "Float" and infer(stmt.value, symbols) == "Int":
                value = f"(double)({value})"
            out.append(f"    const {C_TYPES[stmt.declared_type]} {stmt.name} = {value};")
        elif isinstance(stmt, Show):
            typ, value = infer(stmt.value, symbols), expr_to_c(stmt.value, symbols)
            if typ == "Text": out.append(f'    printf("%s\\n", {value});')
            elif typ == "Int": out.append(f'    printf("%lld\\n", (long long)({value}));')
            elif typ == "Float": out.append(f'    printf("%.15g\\n", (double)({value}));')
            elif typ == "Bool": out.append(f'    printf("%s\\n", ({value}) ? "true" : "false");')
    out += ["    return 0;", "}", ""]
    return "\n".join(out)
